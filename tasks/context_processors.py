from django.db.models import Q
from django.utils import timezone

from .models import Notification, Task
from .permissions import is_manager


def tasktracker_context(request):
    if not request.user.is_authenticated:
        return {
            "is_manager": False,
            "unread_notifications": 0,
            "action_notifications_count": 0,
            "pending_review_count": 0,
            "recent_notifications": [],
        }

    manager = is_manager(request.user)
    unread = request.user.task_notifications.filter(read_at__isnull=True)

    if manager and not request.user.is_superuser:
        unread = unread.exclude(
            Q(kind=Notification.Kind.SUBMITTED_REVIEW)
            & ~Q(task__responsible_manager=request.user)
        )

    today = timezone.localdate()
    action_filter = (
        Q(kind=Notification.Kind.SUBMITTED_REVIEW, task__status=Task.Status.REVIEW)
        | Q(kind=Notification.Kind.REVISION_REQUESTED, task__status=Task.Status.REVISION)
        | Q(
            kind=Notification.Kind.OVERDUE,
            task__status__in=[
                Task.Status.NEW,
                Task.Status.IN_PROGRESS,
                Task.Status.REVISION,
            ],
            task__due_date__lt=today,
        )
    )

    if manager:
        pending_reviews = Task.objects.filter(status=Task.Status.REVIEW)
        if not request.user.is_superuser:
            pending_reviews = pending_reviews.filter(responsible_manager=request.user)
        pending_review_count = pending_reviews.count()
    else:
        pending_review_count = 0

    # Last messages are previewed in the slide-out panel; managers never see
    # unrelated review requests even if they were generated by older versions.
    recent = request.user.task_notifications.select_related("task")
    if manager and not request.user.is_superuser:
        recent = recent.exclude(
            Q(kind=Notification.Kind.SUBMITTED_REVIEW)
            & ~Q(task__responsible_manager=request.user)
        )
    return {
        "is_manager": manager,
        "recent_notifications": list(recent[:7]),
        "unread_notifications": unread.count(),
        "action_notifications_count": unread.filter(action_filter).count(),
        "pending_review_count": pending_review_count,
    }
